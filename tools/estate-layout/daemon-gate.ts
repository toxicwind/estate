#!/usr/bin/env bun
/**
 * daemon-gate — machine gate for the estate's pitchfork daemon registry.
 *
 * The compose tool (bin/pitchfork-compose) fails closed on a daemon NAME
 * claimed by two projects. That check cannot see the failure mode that
 * actually bit us on 2026-10-21: two fragments describing the SAME service
 * under two different names. The live registry had
 *
 *   estate/estate-stream-broker          running   (port 25215)
 *   estate/estate-scripts-stream-broker  available (port 25215)
 *
 * — same dir, same run command, same port, two ids. The stale one came from
 * a partial rename (the FILE was renamed, the daemon ID inside it was not),
 * and the duplicate sat in the registry waiting to fight for port 25215 the
 * moment anything started it.
 *
 * This gate reads the composed pitchfork.toml plus config/ports.env and
 * fails on:
 *
 *   DUPLICATE-SERVICE  two daemon ids with the same (dir, run) — the same
 *                      service declared twice under different names.
 *   PORT-COLLISION     two daemon ids claiming the same port.
 *   PORT-RANGE         a daemon port outside 25000-25999 that is not declared
 *                      in the "platform ports outside the 25xxx service range"
 *                      section of config/ports.env (the documented exceptions).
 *   UNDECLARED-PORT    a daemon port that config/ports.env does not declare —
 *                      the SSOT must cover every daemon, or the SSOT lies.
 *   RETIRED-BRAND      a daemon id or env var still carrying the retired
 *                      "sovereign" brand.
 *
 * Usage:
 *   daemon-gate --root /home/toxic/pens/estate            # human report, exit 1 on error
 *   daemon-gate --root /home/toxic/pens/estate --json out.json
 *   daemon-gate --root /home/toxic/pens/estate --warn     # report, never fail
 */

import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

type Daemon = {
  name: string;
  dir: string;
  run: string;
  port: number | null;
  readyPort: number | null;
  envKeys: string[];
  source: string;
};

type Finding = {
  code: string;
  severity: "error" | "warn" | "info";
  subject: string;
  detail: string;
};

const RANGE_LO = 25000;
const RANGE_HI = 25999;
const RETIRED_BRAND = /sovereign/i;

function parseArgs(argv: string[]): Record<string, string | boolean> {
  const out: Record<string, string | boolean> = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith("--")) continue;
    const key = a.slice(2);
    const next = argv[i + 1];
    if (!next || next.startsWith("--")) out[key] = true;
    else {
      out[key] = next;
      i++;
    }
  }
  return out;
}

/**
 * Minimal reader for the composed pitchfork.toml. The composed file is
 * machine-generated by bin/pitchfork-compose: it is a sequence of
 * `[daemons.<name>]` stanzas whose values are strings, numbers, or an inline
 * `env = { ... }` table. That shape is a small, stable subset, so a focused
 * reader is cheaper and safer here than pulling in a TOML dependency.
 */
function readDaemons(text: string, source: string): Daemon[] {
  const daemons: Daemon[] = [];
  let cur: Daemon | null = null;
  let inEnv = false;
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const head = line.match(/^\[daemons\.([^\]]+)\]$/);
    if (head) {
      cur = {
        name: head[1],
        dir: "",
        run: "",
        port: null,
        readyPort: null,
        envKeys: [],
        source,
      };
      daemons.push(cur);
      inEnv = false;
      continue;
    }
    if (!cur) continue;
    if (inEnv) {
      const m = line.match(/^"?([A-Za-z0-9_]+)"?\s*=/);
      if (m) cur.envKeys.push(m[1]);
      if (line.includes("}")) inEnv = false;
      continue;
    }
    const m = line.match(/^([A-Za-z0-9_]+)\s*=\s*(.*)$/);
    if (!m) continue;
    const [, key, rawVal] = m;
    const str = rawVal.replace(/^"/, "").replace(/",?$/, "").replace(/,$/, "");
    if (key === "dir") cur.dir = str;
    else if (key === "run") cur.run = str;
    else if (key === "port") cur.port = Number(str) || null;
    else if (key === "ready_port") cur.readyPort = Number(str) || null;
    else if (key === "env") {
      inEnv = true;
      for (const m2 of str.matchAll(/"?([A-Za-z0-9_]+)"?\s*=/g))
        cur.envKeys.push(m2[1]);
    }
  }
  return daemons;
}

/**
 * config/ports.env -> { KEY: value }, the set of port NUMBERS the SSOT
 * declares, plus the keys in the platform-exception section.
 *
 * The number set is what "is this port declared?" actually means: the SSOT
 * is a port registry, so a daemon's port is declared when the SSOT assigns
 * that NUMBER to some key — not when the key happens to sit under a
 * particular comment heading. Section position is a formatting detail; the
 * number is the fact.
 */
function readPortsEnv(text: string): {
  ports: Map<string, number>;
  numbers: Set<number>;
  exceptions: Set<string>;
} {
  const ports = new Map<string, number>();
  const numbers = new Set<number>();
  const exceptions = new Set<string>();
  let inExceptionSection = false;
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (line.startsWith("#")) {
      if (/platform ports outside the 25xxx service range/i.test(line))
        inExceptionSection = true;
      continue;
    }
    if (!line) continue;
    const m = line.match(/^([A-Za-z0-9_]+)\s*=\s*(\d+)/);
    if (!m) continue;
    const value = Number(m[2]);
    ports.set(m[1], value);
    numbers.add(value);
    if (inExceptionSection) exceptions.add(m[1]);
  }
  return { ports, numbers, exceptions };
}

function main(): number {
  const args = parseArgs(process.argv.slice(2));
  const root = resolve(String(args.root ?? "/home/toxic/pens/estate"));
  const composedPath = join(root, "pitchfork.toml");
  const portsEnvPath = join(root, "config/ports.env");

  const findings: Finding[] = [];
  if (!existsSync(composedPath)) {
    console.error(`daemon-gate: missing ${composedPath}`);
    return 1;
  }
  if (!existsSync(portsEnvPath)) {
    console.error(`daemon-gate: missing ${portsEnvPath}`);
    return 1;
  }

  const daemons = readDaemons(
    readFileSync(composedPath, "utf8"),
    "pitchfork.toml",
  );
  const { ports, numbers, exceptions } = readPortsEnv(
    readFileSync(portsEnvPath, "utf8"),
  );
  const declaredPorts = numbers;

  // --- duplicate service: same (dir, run) under two ids ----------------------
  const byService = new Map<string, Daemon[]>();
  for (const d of daemons) {
    if (!d.dir && !d.run) continue;
    const key = `${d.dir}\u0000${d.run}`;
    const arr = byService.get(key) ?? [];
    arr.push(d);
    byService.set(key, arr);
  }
  for (const [, group] of byService) {
    if (group.length < 2) continue;
    findings.push({
      code: "DUPLICATE-SERVICE",
      severity: "error",
      subject: group
        .map((d) => d.name)
        .sort()
        .join(" + "),
      detail:
        `the same service is declared under ${group.length} daemon ids ` +
        `(dir=${group[0].dir} run=${group[0].run}). One of them is a stale ` +
        `duplicate that will fight for the same port if it ever starts.`,
    });
  }

  // --- port collision ---------------------------------------------------------
  const byPort = new Map<number, Daemon[]>();
  for (const d of daemons) {
    if (d.port === null) continue;
    const arr = byPort.get(d.port) ?? [];
    arr.push(d);
    byPort.set(d.port, arr);
  }
  for (const [port, group] of byPort) {
    const distinct = new Set(group.map((d) => d.name));
    if (distinct.size < 2) continue;
    findings.push({
      code: "PORT-COLLISION",
      severity: "error",
      subject: `port ${port}`,
      detail: `claimed by ${[...distinct].sort().join(", ")}`,
    });
  }

  // --- 25xxx range ------------------------------------------------------------
  for (const d of daemons) {
    if (d.port === null) continue;
    if (d.port >= RANGE_LO && d.port <= RANGE_HI) continue;
    // A port outside the range is legal when config/ports.env declares it —
    // ideally in the documented platform-ports section, but a declaration
    // anywhere in the SSOT still means the SSOT knows about the port. What
    // is NOT legal is a port the SSOT has never heard of: that is a lie.
    const exceptionKeys = [...ports.entries()]
      .filter(([, v]) => v === d.port)
      .map(([k]) => k);
    const isException = exceptionKeys.some((k) => exceptions.has(k));
    const declared = exceptionKeys.length > 0;
    findings.push({
      code: isException
        ? "PORT-PLATFORM"
        : declared
          ? "PORT-OUT-OF-RANGE"
          : "PORT-RANGE",
      severity: isException ? "info" : declared ? "warn" : "error",
      subject: `${d.name} (port ${d.port})`,
      detail: isException
        ? `declared in config/ports.env as a platform port (${exceptionKeys.join(", ")})`
        : declared
          ? `declared in config/ports.env (${exceptionKeys.join(", ")}) but outside ${RANGE_LO}-${RANGE_HI} and not in the platform-ports section — move the declaration there`
          : `outside ${RANGE_LO}-${RANGE_HI} and not declared in config/ports.env at all`,
    });
  }

  // --- undeclared port --------------------------------------------------------
  for (const d of daemons) {
    if (d.port === null) continue;
    if (declaredPorts.has(d.port)) continue;
    findings.push({
      code: "UNDECLARED-PORT",
      severity: "warn",
      subject: `${d.name} (port ${d.port})`,
      detail:
        "config/ports.env does not declare this port — the SSOT is incomplete",
    });
  }

  // --- retired brand ----------------------------------------------------------
  for (const d of daemons) {
    if (RETIRED_BRAND.test(d.name)) {
      findings.push({
        code: "RETIRED-BRAND",
        severity: "error",
        subject: d.name,
        detail: "daemon id still carries the retired 'sovereign' brand",
      });
    }
    for (const k of d.envKeys) {
      if (RETIRED_BRAND.test(k)) {
        findings.push({
          code: "RETIRED-BRAND",
          severity: "error",
          subject: `${d.name}.env.${k}`,
          detail: "env var still carries the retired 'sovereign' brand",
        });
      }
    }
  }

  const errors = findings.filter((f) => f.severity === "error");
  const warns = findings.filter((f) => f.severity === "warn");
  const report = {
    root,
    daemons: daemons.length,
    errors: errors.length,
    warnings: warns.length,
    findings,
  };

  if (typeof args.json === "string")
    writeFileSync(args.json, JSON.stringify(report, null, 2) + "\n");

  for (const f of findings) {
    const tag =
      f.severity === "error"
        ? "ERROR"
        : f.severity === "warn"
          ? "WARN "
          : "INFO ";
    console.log(`${tag} ${f.code}  ${f.subject}\n      ${f.detail}`);
  }
  console.log(
    `\ndaemon-gate: ${daemons.length} daemons · ${errors.length} errors · ${warns.length} warnings`,
  );
  if (errors.length && !args.warn) {
    console.error("daemon-gate: FAILED");
    return 1;
  }
  console.log("daemon-gate: OK");
  return 0;
}

process.exit(main());
